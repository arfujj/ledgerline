"""Generate the SYNTHETIC NovaPay data room.

Usage: uv run python scripts/generate_dataroom.py [--seed 7] [--out dataroom]
Deterministic: the same seed produces byte-identical files (see dataroom/MANIFEST.json).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from synth import answer_key, metrics
from synth.documents import build_documents
from synth.eventlogs import (
    simulate_disputes,
    simulate_kyc,
    simulate_recon,
    simulate_tickets,
)
from synth.render import render
from synth.world import SYNTHETIC_BANNER, WORLD


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--out", type=Path, default=Path("dataroom"))
    args = ap.parse_args()
    out: Path = args.out
    for child in out.glob("*"):
        if child.name != "README.md":
            shutil.rmtree(child) if child.is_dir() else child.unlink()
    out.mkdir(parents=True, exist_ok=True)

    rng = np.random.default_rng(args.seed)
    kyc = simulate_kyc(WORLD, rng)
    disputes = simulate_disputes(WORLD, rng)
    recon = simulate_recon(WORLD, rng)
    tickets = simulate_tickets(WORLD, rng)
    import pandas as pd

    cutoff = pd.Timestamp(WORLD.data_extract_date) + pd.Timedelta(hours=23, minutes=59)
    kyc, disputes, recon = (df[df.timestamp <= cutoff] for df in (kyc, disputes, recon))
    m = metrics.compute(kyc, disputes, recon, tickets, extract=cutoff)

    logs = out / "event_logs"
    logs.mkdir()
    for name, df in [
        ("kyc_onboarding", kyc),
        ("card_disputes", disputes),
        ("daily_reconciliation", recon),
    ]:
        df = df.sort_values(["case_id", "timestamp"], kind="stable").reset_index(drop=True)
        df.to_parquet(logs / f"{name}.parquet", index=False)
        df.to_csv(logs / f"{name}.csv", index=False)
    (out / "support").mkdir()
    tickets.to_csv(out / "support" / "support_tickets.csv", index=False)
    tickets.to_parquet(out / "support" / "support_tickets.parquet", index=False)

    docs = build_documents(WORLD, m)
    doc_index = []
    for spec in docs:
        path = render(spec, out)
        doc_index.append(
            {
                "doc_id": spec.doc_id,
                "title": spec.title,
                "doc_type": spec.doc_type,
                "version": spec.version,
                "effective": spec.effective,
                "owner": spec.owner,
                "path": str(path.relative_to(out)),
            }
        )
    (out / "INDEX.json").write_text(json.dumps(doc_index, indent=2) + "\n")
    (out / "README.md").write_text(
        f"# NovaPay data room\n\n**{SYNTHETIC_BANNER}**\n\nGenerated by "
        "`scripts/generate_dataroom.py`. Do not edit by hand.\n"
    )

    key = answer_key.build(m, args.seed)
    (out / "_answer_key.json").write_text(json.dumps(key, indent=2, default=str) + "\n")

    files = sorted(p for p in out.rglob("*") if p.is_file() and p.name != "MANIFEST.json")
    manifest = {str(p.relative_to(out)): sha256(p) for p in files}
    (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n")
    n_events = len(kyc) + len(disputes) + len(recon)
    print(
        f"docs={len(docs)} events={n_events:,} tickets={len(tickets):,} "
        f"recon_manual_share={m['recon_manual_share']:.3f} "
        f"kyc_rework={m['kyc_rework_rate']:.3f} dispute_breach={m['dispute_sla_breach_rate']:.3f}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
